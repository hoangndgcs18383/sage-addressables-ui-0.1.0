using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace SAGE.AddressablesUI.Editor
{
    public sealed class AddressCodeEntry
    {
        public string Key;
        public string Address;
        public bool IsResource;
    }

    /// <summary>Pure code generation: no AssetDatabase writes or Addressables mutations.</summary>
    public static class AddressCodeGenerator
    {
        public const string Header = "// <auto-generated by SAGE.AddressablesUI>";
        private static readonly HashSet<string> Keywords = new HashSet<string>(
            ("abstract as base bool break byte case catch char checked class const continue decimal default " +
             "delegate do double else enum event explicit extern false finally fixed float for foreach goto if " +
             "implicit in int interface internal is lock long namespace new null object operator out override " +
             "params private protected public readonly ref return sbyte sealed short sizeof stackalloc static " +
             "string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual " +
             "void volatile while").Split(' '), StringComparer.Ordinal);

        public static void ValidateIdentifier(string name)
        {
            if (name == null || !Regex.IsMatch(name, "^[A-Za-z_][A-Za-z0-9_]*$") || Keywords.Contains(name))
                throw new ArgumentException("Invalid C# identifier: " + name);
        }

        public static string GenerateSource(string namespaceName, string className, string getNameMethod,
            IReadOnlyList<AddressCodeEntry> entries)
        {
            if (string.IsNullOrWhiteSpace(namespaceName)) throw new ArgumentException("Namespace is required.");
            foreach (var part in namespaceName.Split('.')) ValidateIdentifier(part);
            ValidateIdentifier(className);
            ValidateIdentifier(getNameMethod);
            if (getNameMethod == "IsResources" || getNameMethod == className || className == "IsResources")
                throw new ArgumentException("Generated method and class names must be distinct.");
            if (entries == null) throw new ArgumentNullException(nameof(entries));
            var keys = new HashSet<string>(StringComparer.Ordinal);
            var members = new HashSet<string>(StringComparer.Ordinal) { className, getNameMethod, "IsResources" };
            var constants = new List<string>();
            foreach (var item in entries)
            {
                if (item == null || string.IsNullOrWhiteSpace(item.Key) || string.IsNullOrWhiteSpace(item.Address))
                    throw new ArgumentException("Each entry needs a key and address.");
                if (!keys.Add(item.Key)) throw new ArgumentException("Duplicate key: " + item.Key);
                var constant = Regex.Replace(item.Key.ToUpperInvariant(), "[^A-Z0-9_]", "_");
                if (char.IsDigit(constant[0])) constant = "_" + constant;
                if (!members.Add(constant)) throw new ArgumentException("Generated constant collision: " + constant);
                constants.Add(constant);
            }
            var source = new StringBuilder();
            source.AppendLine(Header).AppendLine("// Do not edit manually.");
            source.Append("namespace ").AppendLine(namespaceName).AppendLine("{");
            source.Append("    public static class ").AppendLine(className).AppendLine("    {");
            for (var i = 0; i < entries.Count; i++)
                source.Append("        public const string ").Append(constants[i]).Append(" = ")
                    .Append(Literal(entries[i].Key)).AppendLine(";");
            source.Append("        public static string ").Append(getNameMethod).AppendLine("(string key)");
            source.AppendLine("        {").AppendLine("            switch (key)").AppendLine("            {");
            foreach (var item in entries)
                source.Append("                case ").Append(Literal(item.Key)).Append(": return ")
                    .Append(Literal(item.Address)).AppendLine(";");
            source.AppendLine("                default: return null;").AppendLine("            }").AppendLine("        }");
            source.AppendLine("        public static bool IsResources(string key)");
            source.AppendLine("        {").AppendLine("            switch (key)").AppendLine("            {");
            foreach (var item in entries)
                if (item.IsResource) source.Append("                case ").Append(Literal(item.Key)).AppendLine(": return true;");
            source.AppendLine("                default: return false;").AppendLine("            }").AppendLine("        }");
            return source.AppendLine("    }").AppendLine("}").ToString();
        }

        private static string Literal(string value)
        {
            var output = new StringBuilder("\"");
            foreach (var c in value)
            {
                if (c == '"') output.Append("\\\"");
                else if (c == '\\') output.Append("\\\\");
                else if (char.IsControl(c) || c == '\u2028' || c == '\u2029')
                    output.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                else output.Append(c);
            }
            return output.Append('"').ToString();
        }
    }
}
